// childTables are reached only through their composite-FK parent, so they
// need no index starting with project_id.
var childTables = map[string]string{
	"audience_members": "read through the audience (primary key starts with audience_id)",
	"email_contents":   "read through the email (primary key email_id)",
}

// unpinnedRefs are <x>_id uuid columns of project tables without an FK, with
// the reason that is safe.
var unpinnedRefs = map[string]string{
	"broadcasts.cursor_contact_id": "fan-out keyset position; only compared with contact ids of the same broadcast's project, the contact may be deleted meanwhile",
}

// globalUniques are unique indexes on project tables without project_id.
// Each covers only server-generated or provider-assigned values, so it can
// neither collide across projects on client input nor reveal another
// project's data. Unique indexes on "id" alone are always fine.
var globalUniques = map[string]string{
	"api_keys_prefix_key":                         "random key prefix generated by the server",
	"contacts_unsubscribe_token_key":              "random token generated by the server",
	"email_events_provider_provider_event_id_key": "provider-assigned event id (dedup of provider events)",
	"automation_runs_active_key":                  "server ids (automation, contact) pinned to one project by composite FKs",
	"emails_broadcast_contact_key":                "server ids (broadcast, contact) pinned to one project by composite FKs",
	"emails_automation_run_step_key":              "server id of the run plus step index",
	"webhook_deliveries_endpoint_id_event_id_key": "server ids (endpoint, event) pinned to one project by composite FKs",
	"template_versions_pkey":                      "server template id plus version number",
	"audience_members_pkey":                       "server ids (audience, contact) pinned to one project by composite FKs",
	"email_contents_pkey":                         "server email id",
}

// TestTenantSchemaInvariants checks the migrated schema against the table
// split in tenancy_test.go: every project table has project_id NOT NULL with
// an FK to projects, references other project tables only through FKs that
// include project_id, has an index starting with project_id, and has no
// unique index on client-supplied values across projects.
func TestTenantSchemaInvariants(t *testing.T) {
	t.Parallel()
	pool := testdb.NewMigrated(t)
	ctx := context.Background()

	rows, err := pool.Query(ctx, `
		SELECT c.relname,
		       coalesce((SELECT a.attnotnull AND a.atttypid = 'uuid'::regtype FROM pg_attribute a
		                 WHERE a.attrelid = c.oid AND a.attname = 'project_id' AND NOT a.attisdropped), false),
		       (SELECT count(*) FROM pg_attribute a
		        WHERE a.attrelid = c.oid AND a.attname = 'project_id' AND NOT a.attisdropped) > 0
		FROM pg_class c
		WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('r', 'p')
		ORDER BY 1`)
	if err != nil {
		t.Fatal(err)
	}
	var tables []string
	for rows.Next() {
		var name string
		var notNullUUID, has bool
		if err := rows.Scan(&name, &notNullUUID, &has); err != nil {
			t.Fatal(err)
		}
		tables = append(tables, name)
		_, global := globalTables[name]
		tenant := slices.Contains(tenantTables, name)
		switch {
		case global && tenant:
			t.Errorf("%s is listed as both global and project table", name)
		case !global && !tenant:
			t.Errorf("table %s is not classified; add it to globalTables or tenantTables", name)
		case tenant && !notNullUUID:
			t.Errorf("project table %s needs project_id uuid NOT NULL", name)
		case global && has && name != "projects":
			t.Errorf("global table %s has a project_id column", name)
		}
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	for _, name := range tenantTables {
		if !slices.Contains(tables, name) {
			t.Errorf("stale project table %s", name)
		}
	}
	for name := range globalTables {
		if !slices.Contains(tables, name) {
			t.Errorf("stale global table %s", name)
		}
	}

	// Foreign keys: (table, referenced table, includes project_id on both sides).
	var fks []foreignKey
	rows, err = pool.Query(ctx, `
		SELECT c.conrelid::regclass::text, c.confrelid::regclass::text, c.conname,
		       EXISTS (SELECT 1 FROM unnest(c.conkey) k(n) JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.n
		               WHERE a.attname = 'project_id')
		       AND EXISTS (SELECT 1 FROM unnest(c.confkey) k(n) JOIN pg_attribute a ON a.attrelid = c.confrelid AND a.attnum = k.n
		               WHERE a.attname IN ('project_id', 'id') AND (a.attname = 'project_id' OR c.confrelid = 'projects'::regclass))
		FROM pg_constraint c
		WHERE c.contype = 'f' AND c.connamespace = 'public'::regnamespace`)
	if err != nil {
		t.Fatal(err)
	}
	for rows.Next() {
		var f foreignKey
		if err := rows.Scan(&f.table, &f.ref, &f.name, &f.scoped); err != nil {
			t.Fatal(err)
		}
		fks = append(fks, f)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	for _, name := range tenantTables {
		toProjects := false
		for _, f := range fks {
			if f.table != name {
				continue
			}
			if f.ref == "projects" {
				toProjects = toProjects || f.scoped
				continue
			}
			if !slices.Contains(tenantTables, f.ref) {
				t.Errorf("project table %s references non-project table %s (%s)", name, f.ref, f.name)
			} else if !f.scoped {
				t.Errorf("FK %s from %s to %s does not include project_id on both sides", f.name, name, f.ref)
			}
		}
		// Children get their project through the parent's composite FK.
		if _, child := childTables[name]; !toProjects && !child && !referencesTenant(fks, name) {
			t.Errorf("project table %s has no FK pinning project_id to projects", name)
		}
	}

	// Every uuid column naming another row (<x>_id) is held by an FK that
	// includes project_id, so it cannot point into another project.
	rows, err = pool.Query(ctx, `
		SELECT c.relname, a.attname
		FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
		WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('r', 'p') AND NOT a.attisdropped
		  AND a.attnum > 0 AND a.atttypid = 'uuid'::regtype AND a.attname LIKE '%\_id' AND a.attname <> 'project_id'
		  AND NOT EXISTS (SELECT 1 FROM pg_constraint k
		                  WHERE k.contype = 'f' AND k.conrelid = c.oid AND a.attnum = ANY (k.conkey)
		                    AND EXISTS (SELECT 1 FROM unnest(k.conkey) n JOIN pg_attribute p ON p.attrelid = c.oid AND p.attnum = n
		                                WHERE p.attname = 'project_id'))`)
	if err != nil {
		t.Fatal(err)
	}
	usedRefs := map[string]bool{}
	for rows.Next() {
		var table, column string
		if err := rows.Scan(&table, &column); err != nil {
			t.Fatal(err)
		}
		if !slices.Contains(tenantTables, table) {
			continue
		}
		if _, ok := unpinnedRefs[table+"."+column]; ok {
			usedRefs[table+"."+column] = true
			continue
		}
		t.Errorf("%s.%s names another row but no FK including project_id holds it", table, column)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	for ref := range unpinnedRefs {
		if !usedRefs[ref] {
			t.Errorf("stale unpinnedRefs entry %s", ref)
		}
	}
	var exclusions int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM pg_constraint WHERE contype = 'x' AND connamespace = 'public'::regnamespace`).Scan(&exclusions); err != nil {
		t.Fatal(err)
	}
	if exclusions != 0 {
		t.Errorf("%d exclusion constraints: classify them like unique indexes before allowing them", exclusions)
	}

	// Indexes: leading project_id, and unique indexes without project_id
	// among their key columns (INCLUDE columns do not scope uniqueness).
	type index struct {
		table, name                      string
		lead, unique, hasProject, idOnly bool
	}
	rows, err = pool.Query(ctx, `
		SELECT t.relname, i.relname,
		       coalesce((SELECT a.attname FROM pg_attribute a WHERE a.attrelid = t.oid AND a.attnum = x.indkey[0]) = 'project_id', false),
		       x.indisunique,
		       EXISTS (SELECT 1 FROM unnest((x.indkey::int2[])[0:x.indnkeyatts - 1]) k(n) JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = k.n
		               WHERE a.attname = 'project_id'),
		       coalesce(x.indnatts = 1 AND (SELECT a.attname FROM pg_attribute a WHERE a.attrelid = t.oid AND a.attnum = x.indkey[0]) = 'id', false)
		FROM pg_index x
		JOIN pg_class i ON i.oid = x.indexrelid
		JOIN pg_class t ON t.oid = x.indrelid
		WHERE t.relnamespace = 'public'::regnamespace`)
	if err != nil {
		t.Fatal(err)
	}
	var idx []index
	for rows.Next() {
		var x index
		if err := rows.Scan(&x.table, &x.name, &x.lead, &x.unique, &x.hasProject, &x.idOnly); err != nil {
			t.Fatal(err)
		}
		idx = append(idx, x)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	usedUniques := map[string]bool{}
	for _, name := range tenantTables {
		lead := false
		for _, x := range idx {
			if x.table != name {
				continue
			}
			lead = lead || x.lead
			if x.unique && !x.hasProject && !x.idOnly {
				if _, ok := globalUniques[x.name]; !ok {
					t.Errorf("unique index %s on %s spans projects; include project_id or list it with a reason", x.name, name)
				}
				usedUniques[x.name] = true
			}
		}
		_, child := childTables[name]
		switch {
		case !lead && !child:
			t.Errorf("project table %s has no index starting with project_id", name)
		case lead && child:
			t.Errorf("child table %s has an index starting with project_id; drop it from childTables", name)
		}
	}
	var stale []string
	for name := range globalUniques {
		if !usedUniques[name] {
			stale = append(stale, name)
		}
	}
	sort.Strings(stale)
	if len(stale) > 0 {
		t.Errorf("stale globalUniques entries: %v", stale)
	}
}

// foreignKey is one FK constraint; scoped means it includes project_id on
// both sides (or is the FK to projects itself).
type foreignKey struct {
	table, ref, name string
	scoped           bool
}

// referencesTenant reports whether the table has a project-scoped FK to
// another project table (which in turn is pinned to projects).
func referencesTenant(fks []foreignKey, table string) bool {
	for _, f := range fks {
		if f.table == table && f.scoped && f.ref != "projects" {
			return true
		}
	}
	return false
}
